//! Идентичность сети для стратегий — тонкий фасад над [`crate::engine::net_state`].
//!
//! Само состояние (и разбор шлюза) живёт в `net_state`, где собрано всё
//! сетевое; здесь — привычные имена для вызывающего кода.
//!
//! Зачем вообще: стратегия, снятая на одной сети, неверна на другой (другой
//! DPI, другое число хопов, другие блокировки). Ключ стратегии включает id
//! сети, поэтому записи разных сетей не путаются, а при возврате в знакомую
//! сеть переиспользуются без передиагностики. На Linux id — шлюз из
//! `/proc/net/route`, на Android приходит из `ConnectivityManager`.

use crate::engine::net_state;

/// Текущий id сети. Пустая строка — сеть не определена (единый профиль).
pub fn current() -> String {
    net_state::net_id()
}

/// Задаёт id сети (старт и смена сети).
pub fn set(id: String) {
    net_state::set_net_id(id);
}

/// Шлюз по умолчанию как id сети (Linux-десктоп).
#[cfg(target_os = "linux")]
pub fn detect() -> String {
    net_state::detect_net_id()
}
