//! Автоподбор TTL приманки `fake` — тонкий фасад над [`crate::engine::net_state`].
//!
//! Состояние (подобранный TTL) собрано в `net_state` вместе с остальным сетевым;
//! здесь — привычные имена для боевого пути и диагностики.
//!
//! Идея: приманка должна умереть дальше DPI, но ближе сервера. Нужный TTL —
//! число хопов в это окно, зависит от сети. Диагностика подбирает наибольший
//! TTL с живым рукопожатием и кладёт сюда; бой берёт подобранное вместо
//! конфигового. При смене сети сбрасывается (см. `crate::reset_network_tuning`).

use crate::engine::net_state;

/// TTL для боя: подобранный, если есть, иначе конфиговый.
pub fn effective(config_ttl: u32) -> u32 {
    net_state::effective_fake_ttl(config_ttl)
}

/// Запоминает рабочий TTL (бегущий минимум по доменам сети).
pub fn note_working(ttl: u32) {
    net_state::note_fake_ttl(ttl);
}

/// Текущий подобранный TTL, если есть.
pub fn current() -> Option<u32> {
    net_state::auto_fake_ttl()
}
