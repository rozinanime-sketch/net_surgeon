//! Разбор ответа DNS: адреса и имя вопроса.
//!
//! Ответ приходит от внешнего резолвера, а извлечённые адреса попадают в кэш
//! «адрес → домен», по которому решается, обходить ли соединение. Подделанный
//! ответ не должен ни ронять программу, ни уводить разбор за буфер.
#![no_main]

use libfuzzer_sys::fuzz_target;
use net_surgeon::dns::ip_cache;

fuzz_target!(|data: &[u8]| {
    // Имена в DNS умеют ссылаться друг на друга; зацикленная ссылка не должна
    // вешать разбор — за этим следит счётчик переходов внутри `read_name`.
    let _ = ip_cache::extract_ips_from_dns_response(data);
    let _ = ip_cache::extract_qname(data);
});
